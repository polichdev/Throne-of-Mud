import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';

const source = fs.readFileSync(new URL('../src/components/canvas/buildings/residentialSmoke.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2023 } }).outputText;
const { ResidentialSmokeState } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
const smoke = new ResidentialSmokeState();
const resident = { position: [2, 0.3, 4], path: [], currentJob: { type: 'sleep', targetBuildingId: 'home', targetPosition: [2, 4] } };
let scans = 0;
const residents = { *[Symbol.iterator]() { scans++; yield resident; } };
for (const hour of [6, 12, 19.99]) assert.equal(smoke.hasSleepingResident('home', 1, hour, residents), false);
assert.equal(scans, 0, 'Daytime never scans residents');
assert.equal(smoke.hasSleepingResident('home', 1, 20, residents), true, 'Night begins immediately at 20:00');
assert.equal(smoke.hasSleepingResident('empty-house', 1, 20, residents), false, 'Empty homes do not emit smoke');
assert.equal(smoke.hasSleepingResident(null, 1, 20, residents), false, 'Previews without occupants do not emit smoke');
assert.equal(scans, 1, 'All chimneys share a single scan per sample');
resident.path = [[3, 4]];
assert.equal(smoke.hasSleepingResident('home', 2, 21, residents), false, 'Walking to bed is not sleeping');
resident.path = []; resident.position = [10, 0.3, 4];
assert.equal(smoke.hasSleepingResident('home', 3, 22, residents), false, 'Not yet at the bed');
resident.position = [2, 1.8, 4];
assert.equal(smoke.hasSleepingResident('home', 4, 0, residents), true, 'Upper-floor sleepers count after midnight');
resident.currentJob.type = 'work';
assert.equal(smoke.hasSleepingResident('home', 5, 5, residents), false, 'Awake occupants do not emit residential smoke');
resident.currentJob.type = 'sleep';
assert.equal(smoke.hasSleepingResident('home', 6, 5.99, residents), true);
assert.equal(smoke.hasSleepingResident('home', 6, 6, residents), false, 'Dawn clears smoke even in the same sample');
console.log('Residential smoke: daytime, night boundaries, empty homes, walking, bed arrival, upper floor and shared scan passed.');
